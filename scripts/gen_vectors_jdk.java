// Vectors for `below` and `scalar` from the JDK: a SecureRandom fed the same
// bytes the Go vectors use, and `new BigInteger(bitLength, random)` — the draw
// SunEC makes for an EC private scalar — in a rejection loop.
//
// The loop is five lines; the reading, the masking and the comparison are the
// JDK's. Orders whose bit length is not a multiple of eight are left out:
// `BigInteger` clears the spare bits of the first byte where FIPS 186-5 A.2.2
// shifts the whole number, so P-521 is a documented divergence, not a vector.
//
//	java scripts/gen_vectors_jdk.java > src/vectors_jdk_test.mbt

import java.io.ByteArrayOutputStream;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.SecureRandom;

public final class gen_vectors_jdk {

    /** An endless SHA-256 counter stream, the same shape as the Go generator's. */
    static final class Stream extends SecureRandom {
        private final String seed;
        private final ByteArrayOutputStream used = new ByteArrayOutputStream();
        private long counter;
        private final byte[] pending = new byte[32];
        private int at = 32;

        Stream(String seed) { this.seed = seed; }

        @Override public void nextBytes(byte[] out) {
            for (int i = 0; i < out.length; i++) {
                if (at == 32) {
                    byte[] block = sha256(seed + ":" + counter);
                    counter += 1;
                    System.arraycopy(block, 0, pending, 0, 32);
                    at = 0;
                }
                out[i] = pending[at++];
                used.write(out[i]);
            }
        }

        byte[] used() { return used.toByteArray(); }
    }

    static byte[] sha256(String text) {
        try {
            return MessageDigest.getInstance("SHA-256").digest(text.getBytes(StandardCharsets.UTF_8));
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }

    static String lit(byte[] data) {
        StringBuilder sb = new StringBuilder("b\"");
        for (byte b : data) sb.append(String.format("\\x%02x", b & 0xff));
        return sb.append('"').toString();
    }

    /** The bytes of a positive number, without BigInteger's sign byte. */
    static byte[] unsigned(BigInteger value) {
        byte[] raw = value.toByteArray();
        if (raw.length > 1 && raw[0] == 0) {
            byte[] out = new byte[raw.length - 1];
            System.arraycopy(raw, 1, out, 0, out.length);
            return out;
        }
        return raw;
    }

    /** The value as `width` big-endian bytes. */
    static byte[] padded(BigInteger value, int width) {
        byte[] raw = unsigned(value);
        byte[] out = new byte[width];
        int copy = Math.min(raw.length, width);
        System.arraycopy(raw, raw.length - copy, out, width - copy, copy);
        return out;
    }

    /** Uniform in [0, bound): the JDK's draw, rejected while it is too big. */
    static BigInteger below(Stream stream, BigInteger bound) {
        int bits = bound.subtract(BigInteger.ONE).bitLength();
        while (true) {
            BigInteger draw = new BigInteger(bits, stream);
            if (draw.compareTo(bound) < 0) return draw;
        }
    }

    /** Uniform in [1, order): the draw SunEC makes, rejected on zero and on the order. */
    static BigInteger scalar(Stream stream, BigInteger order) {
        int bits = order.bitLength();
        while (true) {
            BigInteger draw = new BigInteger(bits, stream);
            if (draw.signum() > 0 && draw.compareTo(order) < 0) return draw;
        }
    }

    static final String[] CURVES = {"P-224", "P-256", "P-384"};
    static final String[] ORDERS = {
        "ffffffffffffffffffffffffffffffff000000000000000000000001",
        "ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551",
        "ffffffffffffffffffffffffffffffffffffffffffffffffc7634d81f4372ddf581a0db248b0a77aecec196accc52973",
    };

    public static void main(String[] args) {
        StringBuilder out = new StringBuilder();
        out.append("// Generated by scripts/gen_vectors_jdk.java from the JDK's BigInteger and SecureRandom.\n");
        out.append("// Edit the script, not this file.\n\n");

        BigInteger[] bounds = {
            BigInteger.valueOf(3), BigInteger.valueOf(7), BigInteger.valueOf(139),
            BigInteger.valueOf(1000), BigInteger.valueOf(65535), BigInteger.valueOf(65537),
            new BigInteger("ffffffffffffffff", 16),
            new BigInteger("c9f2c9cd04674edea40000000", 16),
        };
        out.append("///|\n");
        out.append("/// A bound, the bytes the JDK's draw read, and the eight values it returned.\n");
        out.append("let jdk_below_vectors : Array[(Bytes, Bytes, Array[Bytes])] = [\n");
        for (BigInteger bound : bounds) {
            Stream stream = new Stream("moonseed jdk below " + bound.toString(16));
            int width = (bound.subtract(BigInteger.ONE).bitLength() + 7) / 8;
            StringBuilder values = new StringBuilder();
            for (int i = 0; i < 8; i++) {
                if (i > 0) values.append(", ");
                values.append(lit(padded(below(stream, bound), width)));
            }
            out.append("  (").append(lit(unsigned(bound))).append(", ")
               .append(lit(stream.used())).append(", [").append(values).append("]),\n");
        }
        out.append("]\n\n");

        out.append("///|\n");
        out.append("/// A group order, the bytes the JDK's draw read, and the private scalar it made.\n");
        out.append("let jdk_scalar_vectors : Array[(Bytes, Bytes, Bytes)] = [\n");
        for (int c = 0; c < CURVES.length; c++) {
            BigInteger order = new BigInteger(ORDERS[c], 16);
            Stream stream = new Stream("moonseed jdk scalar " + CURVES[c]);
            BigInteger value = scalar(stream, order);
            out.append("  (").append(lit(unsigned(order))).append(", ")
               .append(lit(stream.used())).append(", ")
               .append(lit(padded(value, unsigned(order).length))).append("),\n");
        }
        out.append("]\n\n");

        out.append("///|\n");
        out.append("test \"below returns what the JDK's draw returns, from the same bytes\" {\n");
        out.append("  for v in jdk_below_vectors {\n");
        out.append("    let (bound, stream, values) = v\n");
        out.append("    let source = @moonseed.Replay::new(stream)\n");
        out.append("    for value in values {\n");
        out.append("      assert_eq(@moonseed.below(bound, source), value)\n");
        out.append("    }\n");
        out.append("    assert_eq(source.remaining(), 0)\n");
        out.append("  }\n");
        out.append("}\n\n");
        out.append("///|\n");
        out.append("test \"scalar returns the scalar the JDK's draw makes, from the same bytes\" {\n");
        out.append("  for v in jdk_scalar_vectors {\n");
        out.append("    let (order, stream, key) = v\n");
        out.append("    let source = @moonseed.Replay::new(stream)\n");
        out.append("    assert_eq(@moonseed.scalar(order, source), key)\n");
        out.append("    assert_eq(source.remaining(), 0)\n");
        out.append("  }\n");
        out.append("}\n");
        System.out.print(out);
    }
}
